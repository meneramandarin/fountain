#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

import { closePool, query } from "../pipeline/lib/db.mjs";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const inputPath = path.resolve(process.argv[2] || path.join(ROOT, "tmp/capped-treatment-resolutions-audited.jsonl"));
const outputPath = path.resolve(process.argv[3] || path.join(ROOT, "migrations/20260812_apply_capped_treatment_taxonomy.sql"));
const MAX_TREATMENTS = 300;

const resolutions = (await readFile(inputPath, "utf8"))
  .split(/\r?\n/u)
  .filter(Boolean)
  .map((line) => JSON.parse(line))
  .sort((a, b) => a.term_normalized.localeCompare(b.term_normalized));
const existingTreatments = (await query(`SELECT id, canonical_name, category FROM fountain.treatments ORDER BY id`)).rows;
await closePool();

const existingIds = new Set(existingTreatments.map((row) => Number(row.id)));
const existingNormalizedNames = new Set(existingTreatments.map((row) => normalize(row.canonical_name)));
const usedNewFamilies = new Map();
const seenTerms = new Set();
for (const row of resolutions) {
  if (!row.term_normalized || seenTerms.has(row.term_normalized)) throw new Error(`Duplicate or empty term: ${row.term_normalized}`);
  seenTerms.add(row.term_normalized);
  if (row.kind === "existing" && !existingIds.has(Number(row.treatment_id))) {
    throw new Error(`Missing existing treatment ${row.treatment_id} for ${row.term_normalized}`);
  }
  if (row.kind === "new") {
    const key = normalize(row.new_treatment_name);
    const prior = usedNewFamilies.get(key);
    if (prior && (prior.name !== row.new_treatment_name || prior.category !== row.category)) {
      throw new Error(`Conflicting new family ${row.new_treatment_name}`);
    }
    usedNewFamilies.set(key, { name: row.new_treatment_name, category: row.category });
  }
  if (!['existing', 'new', 'non_service'].includes(row.kind)) throw new Error(`Invalid kind: ${row.kind}`);
}

const genuinelyNewFamilyCount = [...usedNewFamilies.keys()].filter((key) => !existingNormalizedNames.has(key)).length;
if (existingTreatments.length + genuinelyNewFamilyCount > MAX_TREATMENTS) {
  throw new Error(`Migration would create ${existingTreatments.length + genuinelyNewFamilyCount} treatments.`);
}

const payload = JSON.stringify(resolutions.map((row) => ({
  term_normalized: row.term_normalized,
  display_term: row.original_name,
  english_term: row.english_name,
  occurrence_count: Number(row.occurrence_count || 0),
  target_kind: row.kind,
  existing_treatment_id: row.kind === "existing" ? Number(row.treatment_id) : null,
  proposed_canonical_name: row.kind === "new" ? row.new_treatment_name : null,
  broad_category: row.kind === "non_service" ? "Out of scope" : row.category,
  confidence: Number(row.confidence || 0),
  rationale: String(row.rationale || "Capped controlled-vocabulary resolution.").slice(0, 500),
}))).replaceAll("$capped_taxonomy$", "$capped taxonomy$");

const sql = `-- Assign every active uncategorized menu item to a deliberately capped
-- controlled treatment vocabulary. Original menu labels remain unchanged.
-- Non-services remain visible in source data but are explicitly classified
-- out of taxonomy. Generated by scripts/generate-capped-treatment-migration.mjs.

BEGIN;

SELECT fountain.set_mutation_actor(
  'd5608f46-d9fb-4144-a2a7-202608120001'::uuid,
  'apply_capped_treatment_taxonomy_20260812'
);

CREATE TEMP TABLE capped_term_resolutions (
  term_normalized text PRIMARY KEY,
  display_term text NOT NULL,
  english_term text NOT NULL,
  occurrence_count integer NOT NULL,
  target_kind text NOT NULL CHECK (target_kind IN ('existing', 'new', 'non_service')),
  existing_treatment_id integer,
  proposed_canonical_name text,
  broad_category text NOT NULL,
  confidence double precision NOT NULL CHECK (confidence BETWEEN 0 AND 1),
  rationale text NOT NULL,
  CHECK (
    (target_kind = 'existing' AND existing_treatment_id IS NOT NULL AND proposed_canonical_name IS NULL)
    OR (target_kind = 'new' AND existing_treatment_id IS NULL AND proposed_canonical_name IS NOT NULL)
    OR (target_kind = 'non_service' AND existing_treatment_id IS NULL AND proposed_canonical_name IS NULL)
  )
) ON COMMIT DROP;

INSERT INTO capped_term_resolutions
SELECT *
FROM jsonb_to_recordset($capped_taxonomy$${payload}$capped_taxonomy$::jsonb) AS row(
  term_normalized text,
  display_term text,
  english_term text,
  occurrence_count integer,
  target_kind text,
  existing_treatment_id integer,
  proposed_canonical_name text,
  broad_category text,
  confidence double precision,
  rationale text
);

DO $$
BEGIN
  IF (SELECT count(*) FROM capped_term_resolutions) <> ${resolutions.length} THEN
    RAISE EXCEPTION 'Capped taxonomy payload did not load completely';
  END IF;
  IF EXISTS (
    SELECT 1 FROM capped_term_resolutions
    WHERE target_kind <> 'non_service'
      AND broad_category NOT IN ('Measure', 'Optimize', 'Recover', 'Regenerate', 'Rejuvenate')
  ) THEN
    RAISE EXCEPTION 'A service lacks a valid Fountain category';
  END IF;
  IF EXISTS (
    SELECT 1
    FROM capped_term_resolutions resolution
    LEFT JOIN fountain.treatments treatment ON treatment.id = resolution.existing_treatment_id
    WHERE resolution.target_kind = 'existing' AND treatment.id IS NULL
  ) THEN
    RAISE EXCEPTION 'A resolution references a missing existing treatment';
  END IF;
END;
$$;

CREATE TABLE IF NOT EXISTS fountain_raw.capped_offering_assignment_backup_20260812 AS
SELECT offering.*, now() AS backed_up_at
FROM fountain.offerings offering
JOIN capped_term_resolutions resolution
  ON resolution.term_normalized = fountain_raw.normalize_treatment_term(offering.raw_name)
WHERE offering.status = 'active'
  AND offering.deleted_at IS NULL
  AND offering.treatment_id IS NULL;

CREATE TABLE IF NOT EXISTS fountain_raw.capped_term_classification_backup_20260812 AS
SELECT classification.*, now() AS backed_up_at
FROM fountain_raw.treatment_term_classifications classification
JOIN capped_term_resolutions USING (term_normalized);

CREATE TABLE IF NOT EXISTS fountain_raw.capped_offering_classification_backup_20260812 AS
SELECT classification.*, now() AS backed_up_at
FROM fountain.offering_taxonomy_classifications classification
JOIN capped_term_resolutions USING (term_normalized);

CREATE TEMP TABLE used_new_families ON COMMIT DROP AS
SELECT DISTINCT
  fountain_raw.normalize_treatment_term(proposed_canonical_name) AS family_normalized,
  proposed_canonical_name,
  broad_category
FROM capped_term_resolutions
WHERE target_kind = 'new';

DO $$
BEGIN
  IF EXISTS (
    SELECT family_normalized
    FROM used_new_families
    GROUP BY family_normalized
    HAVING count(DISTINCT concat(proposed_canonical_name, ':', broad_category)) <> 1
  ) THEN
    RAISE EXCEPTION 'A proposed family has conflicting names or categories';
  END IF;
END;
$$;

INSERT INTO fountain.treatments (canonical_name, description, category)
SELECT
  family.proposed_canonical_name,
  concat('Canonical treatment family for ', lower(family.proposed_canonical_name), ' services.'),
  family.broad_category
FROM used_new_families family
WHERE NOT EXISTS (
  SELECT 1 FROM fountain.treatments treatment
  WHERE fountain_raw.normalize_treatment_term(treatment.canonical_name) = family.family_normalized
)
ON CONFLICT (canonical_name) DO NOTHING;

DO $$
BEGIN
  IF (SELECT count(*) FROM fountain.treatments) > ${MAX_TREATMENTS} THEN
    RAISE EXCEPTION 'Treatment vocabulary exceeded the hard cap of ${MAX_TREATMENTS}';
  END IF;
END;
$$;

CREATE TEMP TABLE resolved_term_targets ON COMMIT DROP AS
SELECT
  resolution.*,
  CASE
    WHEN resolution.target_kind = 'existing' THEN resolution.existing_treatment_id
    WHEN resolution.target_kind = 'new' THEN treatment.id
    ELSE NULL
  END AS resolved_treatment_id,
  CASE WHEN resolution.target_kind = 'non_service' THEN 'Out of scope' ELSE treatment.category END AS resolved_category
FROM capped_term_resolutions resolution
LEFT JOIN fountain.treatments treatment
  ON resolution.target_kind = 'new'
 AND fountain_raw.normalize_treatment_term(treatment.canonical_name)
     = fountain_raw.normalize_treatment_term(resolution.proposed_canonical_name);

UPDATE resolved_term_targets target
SET resolved_category = treatment.category
FROM fountain.treatments treatment
WHERE target.target_kind = 'existing'
  AND treatment.id = target.resolved_treatment_id;

DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM resolved_term_targets
    WHERE target_kind <> 'non_service'
      AND (resolved_treatment_id IS NULL OR resolved_category IS NULL)
  ) THEN
    RAISE EXCEPTION 'A genuine service failed to resolve to a treatment';
  END IF;
END;
$$;

-- A previously classified Rife row predates this cleanup and carries the
-- wrong Preventive Care tag. Keep its original state recoverable, then make
-- the exact label agree with the authoritative term-level resolution.
CREATE TABLE IF NOT EXISTS fountain_raw.capped_explicit_override_backup_20260812 AS
SELECT offering.*, now() AS backed_up_at
FROM fountain.offerings offering
JOIN resolved_term_targets target
  ON target.term_normalized = fountain_raw.normalize_treatment_term(offering.raw_name)
WHERE offering.status = 'active'
  AND offering.deleted_at IS NULL
  AND target.term_normalized = 'rife therapy'
  AND offering.treatment_id IS DISTINCT FROM target.resolved_treatment_id;

CREATE TABLE IF NOT EXISTS fountain_raw.capped_alias_backup_20260812 AS
SELECT alias.*, now() AS backed_up_at
FROM fountain_raw.treatment_aliases alias
JOIN resolved_term_targets target
  ON target.term_normalized = alias.alias_normalized
WHERE alias.mapping_status = 'active'
  AND target.target_kind <> 'non_service'
  AND alias.treatment_id <> target.resolved_treatment_id;

UPDATE fountain_raw.treatment_aliases alias
SET mapping_status = 'rejected',
    mapping_reviewed_at = now(),
    mapping_review_model = 'openai/gpt-5.5+capped_rules',
    mapping_review_rationale = 'Superseded by the capped controlled-vocabulary resolution.'
FROM resolved_term_targets target
WHERE target.term_normalized = alias.alias_normalized
  AND target.target_kind <> 'non_service'
  AND alias.mapping_status = 'active'
  AND alias.treatment_id <> target.resolved_treatment_id;

INSERT INTO fountain_raw.treatment_aliases (
  id, treatment_id, alias_text, alias_normalized, source_slug,
  mapping_status, mapping_confidence, mapping_review_model,
  mapping_reviewed_at, mapping_review_rationale
)
SELECT
  nextval(pg_get_serial_sequence('fountain_raw.treatment_aliases', 'id'))::integer,
  target.resolved_treatment_id,
  target.display_term,
  target.term_normalized,
  'capped_treatment_taxonomy_20260812',
  'active',
  target.confidence,
  'openai/gpt-5.5+capped_rules',
  now(),
  target.rationale
FROM resolved_term_targets target
WHERE target.target_kind <> 'non_service'
  AND NOT EXISTS (
    SELECT 1 FROM fountain_raw.treatment_aliases alias
    WHERE alias.alias_normalized = target.term_normalized
      AND alias.treatment_id = target.resolved_treatment_id
      AND alias.mapping_status = 'active'
  );

INSERT INTO fountain_raw.treatment_term_classifications (
  term_normalized, display_term, disposition, treatment_id, broad_category,
  confidence, method, model, rationale, occurrence_count,
  classified_at, updated_at
)
SELECT
  target.term_normalized,
  target.display_term,
  CASE WHEN target.target_kind = 'non_service' THEN 'non_service' ELSE 'mapped_existing' END,
  target.resolved_treatment_id,
  target.resolved_category,
  target.confidence,
  'capped_controlled_vocabulary',
  'openai/gpt-5.5',
  target.rationale,
  target.occurrence_count,
  now(),
  now()
FROM resolved_term_targets target
ON CONFLICT (term_normalized) DO UPDATE SET
  display_term = EXCLUDED.display_term,
  disposition = EXCLUDED.disposition,
  treatment_id = EXCLUDED.treatment_id,
  broad_category = EXCLUDED.broad_category,
  confidence = EXCLUDED.confidence,
  method = EXCLUDED.method,
  model = EXCLUDED.model,
  rationale = EXCLUDED.rationale,
  occurrence_count = EXCLUDED.occurrence_count,
  classified_at = now(),
  updated_at = now();

UPDATE fountain.offerings offering
SET treatment_id = target.resolved_treatment_id,
    updated_at = now()
FROM resolved_term_targets target
WHERE target.term_normalized = fountain_raw.normalize_treatment_term(offering.raw_name)
  AND target.target_kind <> 'non_service'
  AND offering.status = 'active'
  AND offering.deleted_at IS NULL
  AND (
    offering.treatment_id IS NULL
    OR target.term_normalized = 'rife therapy'
  );

UPDATE fountain.offering_taxonomy_classifications classification
SET treatment_id = target.resolved_treatment_id,
    broad_category = target.resolved_category,
    confidence = target.confidence,
    method = 'capped_controlled_vocabulary',
    model = 'openai/gpt-5.5',
    rationale = target.rationale,
    classified_at = now(),
    updated_at = now()
FROM fountain.offerings offering
JOIN resolved_term_targets target
  ON target.term_normalized = fountain_raw.normalize_treatment_term(offering.raw_name)
WHERE classification.offering_id = offering.id
  AND target.term_normalized = 'rife therapy'
  AND offering.status = 'active'
  AND offering.deleted_at IS NULL;

INSERT INTO fountain.offering_taxonomy_classifications (
  offering_id, term_normalized, disposition, treatment_id, broad_category,
  confidence, method, model, rationale, classified_at, updated_at
)
SELECT
  offering.id,
  target.term_normalized,
  'non_service',
  NULL,
  'Out of scope',
  target.confidence,
  'capped_controlled_vocabulary',
  'openai/gpt-5.5',
  target.rationale,
  now(),
  now()
FROM fountain.offerings offering
JOIN resolved_term_targets target
  ON target.term_normalized = fountain_raw.normalize_treatment_term(offering.raw_name)
WHERE target.target_kind = 'non_service'
  AND offering.status = 'active'
  AND offering.deleted_at IS NULL
ON CONFLICT (offering_id) DO UPDATE SET
  term_normalized = EXCLUDED.term_normalized,
  disposition = EXCLUDED.disposition,
  treatment_id = NULL,
  broad_category = EXCLUDED.broad_category,
  confidence = EXCLUDED.confidence,
  method = EXCLUDED.method,
  model = EXCLUDED.model,
  rationale = EXCLUDED.rationale,
  classified_at = now(),
  updated_at = now();

CREATE TABLE IF NOT EXISTS fountain_raw.capped_treatment_resolution_20260812 AS
SELECT target.*, now() AS applied_at
FROM resolved_term_targets target;

SELECT fountain.refresh_city_index();

DO $$
BEGIN
  IF EXISTS (
    SELECT 1
    FROM fountain.offerings offering
    LEFT JOIN fountain.offering_taxonomy_classifications classification
      ON classification.offering_id = offering.id
    WHERE offering.status = 'active'
      AND offering.deleted_at IS NULL
      AND offering.treatment_id IS NULL
      AND coalesce(classification.disposition, '') <> 'non_service'
  ) THEN
    RAISE EXCEPTION 'An active uncategorized offering remains unresolved';
  END IF;
  IF EXISTS (
    SELECT 1
    FROM fountain.offerings offering
    JOIN fountain.treatments treatment ON treatment.id = offering.treatment_id
    WHERE offering.status = 'active'
      AND offering.deleted_at IS NULL
      AND treatment.category NOT IN ('Measure', 'Optimize', 'Recover', 'Regenerate', 'Rejuvenate')
  ) THEN
    RAISE EXCEPTION 'An active offering maps outside the five Fountain categories';
  END IF;
END;
$$;

COMMIT;
`;

await writeFile(outputPath, sql, "utf8");
console.log(JSON.stringify({
  terms: resolutions.length,
  existing_treatments: existingTreatments.length,
  used_new_families: usedNewFamilies.size,
  genuinely_new_families: genuinelyNewFamilyCount,
  resulting_treatments: existingTreatments.length + genuinelyNewFamilyCount,
  bytes: Buffer.byteLength(sql),
  output: path.relative(ROOT, outputPath),
}, null, 2));

function normalize(value) {
  return String(value || "").toLowerCase().normalize("NFKD").replace(/[^a-z0-9]+/gu, " ").trim();
}
