DO $$
DECLARE
    schema_name TEXT := '__CANONICAL_SCHEMA__';
    target_table TEXT;
    constraint_name TEXT;
BEGIN
    FOREACH target_table IN ARRAY ARRAY[
        'organizations',
        'locations',
        'practitioners',
        'documents',
        'affiliations',
        'offerings',
        'images',
        'reviews'
    ] LOOP
        constraint_name := target_table || '_owner_account_fk';
        IF NOT EXISTS (
            SELECT 1
            FROM pg_constraint c
            JOIN pg_namespace n ON n.oid = c.connamespace
            WHERE n.nspname = schema_name
              AND c.conname = constraint_name
        ) THEN
            EXECUTE format(
                'ALTER TABLE %I.%I ADD CONSTRAINT %I FOREIGN KEY (owner_account_id) REFERENCES %I.accounts(id) ON DELETE SET NULL',
                schema_name,
                target_table,
                constraint_name,
                schema_name
            );
        END IF;

        constraint_name := target_table || '_status_valid';
        IF NOT EXISTS (
            SELECT 1
            FROM pg_constraint c
            JOIN pg_namespace n ON n.oid = c.connamespace
            WHERE n.nspname = schema_name
              AND c.conname = constraint_name
        ) THEN
            EXECUTE format(
                'ALTER TABLE %I.%I ADD CONSTRAINT %I CHECK (status IN (''active'', ''pending'', ''draft'', ''hidden'', ''deleted'')) NOT VALID',
                schema_name,
                target_table,
                constraint_name
            );
        END IF;
        EXECUTE format('ALTER TABLE %I.%I VALIDATE CONSTRAINT %I', schema_name, target_table, constraint_name);

        constraint_name := target_table || '_data_origin_valid';
        IF NOT EXISTS (
            SELECT 1
            FROM pg_constraint c
            JOIN pg_namespace n ON n.oid = c.connamespace
            WHERE n.nspname = schema_name
              AND c.conname = constraint_name
        ) THEN
            EXECUTE format(
                'ALTER TABLE %I.%I ADD CONSTRAINT %I CHECK (data_origin IN (''imported'', ''scraped'', ''manual'', ''owner'', ''system'')) NOT VALID',
                schema_name,
                target_table,
                constraint_name
            );
        END IF;
        EXECUTE format('ALTER TABLE %I.%I VALIDATE CONSTRAINT %I', schema_name, target_table, constraint_name);
    END LOOP;
END $$;

