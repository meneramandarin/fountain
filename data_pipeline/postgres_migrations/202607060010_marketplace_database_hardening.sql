CREATE OR REPLACE FUNCTION __CANONICAL_SCHEMA__.refresh_search_index_for_location(p_location_id INTEGER)
RETURNS void
LANGUAGE plpgsql
AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM __CANONICAL_SCHEMA__.locations l
        WHERE l.id = p_location_id
          AND l.status = 'active'
          AND l.deleted_at IS NULL
    ) THEN
        DELETE FROM __CANONICAL_SCHEMA__.search_index
        WHERE entity_type = 'location'
          AND entity_id = p_location_id;
        RETURN;
    END IF;

    INSERT INTO __CANONICAL_SCHEMA__.search_index(
        entity_type,
        entity_id,
        name,
        locality,
        country,
        treatments,
        specialties,
        tags
    )
    SELECT
        'location',
        l.id,
        COALESCE(l.name, org.canonical_name),
        l.locality,
        COALESCE(l.country_name, l.country_code),
        COALESCE((
            SELECT string_agg(DISTINCT COALESCE(t.canonical_name, o.raw_name), ' ' ORDER BY COALESCE(t.canonical_name, o.raw_name))
            FROM __CANONICAL_SCHEMA__.offerings o
            LEFT JOIN __CANONICAL_SCHEMA__.treatments t ON t.id = o.treatment_id
            WHERE o.location_id = l.id
              AND o.status = 'active'
              AND o.deleted_at IS NULL
              AND COALESCE(t.canonical_name, o.raw_name) IS NOT NULL
              AND COALESCE(t.canonical_name, o.raw_name) <> ''
        ), ''),
        '',
        COALESCE((
            SELECT string_agg(DISTINCT tg.facet || ':' || tg.value, ' ' ORDER BY tg.facet || ':' || tg.value)
            FROM __CANONICAL_SCHEMA__.entity_tags et
            JOIN __CANONICAL_SCHEMA__.tags tg ON tg.id = et.tag_id
            WHERE et.entity_type = 'location'
              AND et.entity_id = l.id
        ), '')
    FROM __CANONICAL_SCHEMA__.locations l
    LEFT JOIN __CANONICAL_SCHEMA__.organizations org ON org.id = l.org_id
    WHERE l.id = p_location_id
    ON CONFLICT (entity_type, entity_id) DO UPDATE SET
        name = EXCLUDED.name,
        locality = EXCLUDED.locality,
        country = EXCLUDED.country,
        treatments = EXCLUDED.treatments,
        specialties = EXCLUDED.specialties,
        tags = EXCLUDED.tags;
END;
$$;

CREATE OR REPLACE FUNCTION __CANONICAL_SCHEMA__.refresh_search_index_for_practitioner(p_practitioner_id INTEGER)
RETURNS void
LANGUAGE plpgsql
AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM __CANONICAL_SCHEMA__.practitioners p
        WHERE p.id = p_practitioner_id
          AND p.status = 'active'
          AND p.deleted_at IS NULL
    ) THEN
        DELETE FROM __CANONICAL_SCHEMA__.search_index
        WHERE entity_type = 'practitioner'
          AND entity_id = p_practitioner_id;
        RETURN;
    END IF;

    INSERT INTO __CANONICAL_SCHEMA__.search_index(
        entity_type,
        entity_id,
        name,
        locality,
        country,
        treatments,
        specialties,
        tags
    )
    SELECT
        'practitioner',
        p.id,
        p.full_name,
        COALESCE((
            SELECT string_agg(DISTINCT l.locality, ' ' ORDER BY l.locality)
            FROM __CANONICAL_SCHEMA__.affiliations a
            JOIN __CANONICAL_SCHEMA__.locations l ON l.id = a.location_id
            WHERE a.practitioner_id = p.id
              AND a.status = 'active'
              AND a.deleted_at IS NULL
              AND l.status = 'active'
              AND l.deleted_at IS NULL
              AND l.locality IS NOT NULL
              AND l.locality <> ''
        ), ''),
        COALESCE((
            SELECT string_agg(DISTINCT COALESCE(l.country_name, l.country_code), ' ' ORDER BY COALESCE(l.country_name, l.country_code))
            FROM __CANONICAL_SCHEMA__.affiliations a
            JOIN __CANONICAL_SCHEMA__.locations l ON l.id = a.location_id
            WHERE a.practitioner_id = p.id
              AND a.status = 'active'
              AND a.deleted_at IS NULL
              AND l.status = 'active'
              AND l.deleted_at IS NULL
              AND COALESCE(l.country_name, l.country_code) IS NOT NULL
              AND COALESCE(l.country_name, l.country_code) <> ''
        ), ''),
        '',
        concat_ws(' ', p.primary_specialty, p.credentials, p.languages),
        COALESCE((
            SELECT string_agg(DISTINCT tg.facet || ':' || tg.value, ' ' ORDER BY tg.facet || ':' || tg.value)
            FROM __CANONICAL_SCHEMA__.entity_tags et
            JOIN __CANONICAL_SCHEMA__.tags tg ON tg.id = et.tag_id
            WHERE et.entity_type = 'practitioner'
              AND et.entity_id = p.id
        ), '')
    FROM __CANONICAL_SCHEMA__.practitioners p
    WHERE p.id = p_practitioner_id
    ON CONFLICT (entity_type, entity_id) DO UPDATE SET
        name = EXCLUDED.name,
        locality = EXCLUDED.locality,
        country = EXCLUDED.country,
        treatments = EXCLUDED.treatments,
        specialties = EXCLUDED.specialties,
        tags = EXCLUDED.tags;
END;
$$;

