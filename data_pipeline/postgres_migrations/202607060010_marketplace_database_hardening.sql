DO $$
DECLARE
    schema_name TEXT := '__CANONICAL_SCHEMA__';
    target_table TEXT;
    max_id BIGINT;
    sequence_name TEXT;
BEGIN
    FOREACH target_table IN ARRAY ARRAY[
        'sources',
        'organizations',
        'locations',
        'practitioners',
        'documents',
        'categories',
        'treatments',
        'affiliations',
        'treatment_aliases',
        'offerings',
        'tags',
        'entity_tags',
        'source_records',
        'images',
        'reviews',
        'external_reviews',
        'unmapped_terms'
    ] LOOP
        IF to_regclass(format('%I.%I', schema_name, target_table)) IS NULL THEN
            CONTINUE;
        END IF;

        IF EXISTS (
            SELECT 1
            FROM information_schema.columns
            WHERE table_schema = schema_name
              AND table_name = target_table
              AND column_name = 'id'
              AND is_identity = 'NO'
              AND column_default IS NULL
        ) THEN
            EXECUTE format(
                'ALTER TABLE %I.%I ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY',
                schema_name,
                target_table
            );
        END IF;

        SELECT pg_get_serial_sequence(format('%I.%I', schema_name, target_table), 'id')
        INTO sequence_name;

        IF sequence_name IS NOT NULL THEN
            EXECUTE format('SELECT COALESCE(MAX(id), 0) FROM %I.%I', schema_name, target_table)
            INTO max_id;

            IF max_id > 0 THEN
                PERFORM setval(sequence_name::regclass, max_id, true);
            ELSE
                PERFORM setval(sequence_name::regclass, 1, false);
            END IF;
        END IF;
    END LOOP;
END $$;

