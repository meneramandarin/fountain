CREATE OR REPLACE FUNCTION __CANONICAL_SCHEMA__.touch_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION __CANONICAL_SCHEMA__.audit_entity_change()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    actor_id_text TEXT;
    safe_actor_id UUID;
BEGIN
    actor_id_text := current_setting('fountain.actor_id', true);
    IF actor_id_text ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$' THEN
        safe_actor_id := actor_id_text::uuid;
    END IF;

    INSERT INTO __CANONICAL_SCHEMA__.entity_change_events(
        entity_type,
        entity_id,
        action,
        actor_type,
        actor_id,
        before_data,
        after_data
    )
    VALUES (
        TG_TABLE_NAME,
        CASE WHEN TG_OP = 'DELETE' THEN OLD.id ELSE NEW.id END,
        lower(TG_OP),
        COALESCE(NULLIF(current_setting('fountain.actor_type', true), ''), 'system'),
        safe_actor_id,
        CASE WHEN TG_OP = 'INSERT' THEN NULL ELSE to_jsonb(OLD) END,
        CASE WHEN TG_OP = 'DELETE' THEN NULL ELSE to_jsonb(NEW) END
    );

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;

