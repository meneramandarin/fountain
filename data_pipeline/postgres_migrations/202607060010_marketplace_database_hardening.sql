CREATE OR REPLACE FUNCTION __CANONICAL_SCHEMA__.delete_location_cascade(
    p_location_id INTEGER,
    p_actor_id UUID DEFAULT NULL,
    p_reason TEXT DEFAULT NULL
)
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
    affected_practitioner_id INTEGER;
BEGIN
    IF NOT EXISTS (SELECT 1 FROM __CANONICAL_SCHEMA__.locations WHERE id = p_location_id) THEN
        RAISE EXCEPTION 'Location % does not exist', p_location_id;
    END IF;

    PERFORM __CANONICAL_SCHEMA__.set_mutation_actor(p_actor_id, 'admin');

    CREATE TEMP TABLE IF NOT EXISTS fountain_affected_practitioners(
        practitioner_id INTEGER PRIMARY KEY
    ) ON COMMIT DROP;
    TRUNCATE fountain_affected_practitioners;

    INSERT INTO fountain_affected_practitioners(practitioner_id)
    SELECT DISTINCT practitioner_id
    FROM __CANONICAL_SCHEMA__.affiliations
    WHERE location_id = p_location_id
    ON CONFLICT DO NOTHING;

    DELETE FROM __CANONICAL_SCHEMA__.search_index
    WHERE entity_type = 'location'
      AND entity_id = p_location_id;

    DELETE FROM __CANONICAL_SCHEMA__.images
    WHERE entity_type = 'location'
      AND entity_id = p_location_id;

    DELETE FROM __CANONICAL_SCHEMA__.entity_tags
    WHERE entity_type = 'location'
      AND entity_id = p_location_id;

    DELETE FROM __CANONICAL_SCHEMA__.source_records
    WHERE entity_type = 'location'
      AND entity_id = p_location_id;

    DELETE FROM __CANONICAL_SCHEMA__.external_reviews
    WHERE location_id = p_location_id;

    DELETE FROM __CANONICAL_SCHEMA__.external_place_matches
    WHERE location_id = p_location_id;

    DELETE FROM __CANONICAL_SCHEMA__.reviews
    WHERE location_id = p_location_id;

    DELETE FROM __CANONICAL_SCHEMA__.offerings
    WHERE location_id = p_location_id;

    DELETE FROM __CANONICAL_SCHEMA__.affiliations
    WHERE location_id = p_location_id;

    DELETE FROM __CANONICAL_SCHEMA__.locations
    WHERE id = p_location_id;

    INSERT INTO __CANONICAL_SCHEMA__.entity_change_events(entity_type, entity_id, action, actor_type, actor_id, reason)
    VALUES ('location', p_location_id, 'delete_location_cascade', 'admin', p_actor_id, p_reason);

    FOR affected_practitioner_id IN SELECT practitioner_id FROM fountain_affected_practitioners LOOP
        PERFORM __CANONICAL_SCHEMA__.refresh_search_index_for_practitioner(affected_practitioner_id);
    END LOOP;
END;
$$;

CREATE OR REPLACE FUNCTION __CANONICAL_SCHEMA__.merge_locations(
    p_keep_location_id INTEGER,
    p_delete_location_id INTEGER,
    p_actor_id UUID DEFAULT NULL,
    p_reason TEXT DEFAULT NULL
)
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
    affected_practitioner_id INTEGER;
BEGIN
    IF p_keep_location_id = p_delete_location_id THEN
        RAISE EXCEPTION 'Cannot merge location % into itself', p_keep_location_id;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM __CANONICAL_SCHEMA__.locations WHERE id = p_keep_location_id) THEN
        RAISE EXCEPTION 'Keep location % does not exist', p_keep_location_id;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM __CANONICAL_SCHEMA__.locations WHERE id = p_delete_location_id) THEN
        RAISE EXCEPTION 'Delete location % does not exist', p_delete_location_id;
    END IF;

    PERFORM __CANONICAL_SCHEMA__.set_mutation_actor(p_actor_id, 'admin');

    CREATE TEMP TABLE IF NOT EXISTS fountain_affected_practitioners(
        practitioner_id INTEGER PRIMARY KEY
    ) ON COMMIT DROP;
    TRUNCATE fountain_affected_practitioners;

    INSERT INTO fountain_affected_practitioners(practitioner_id)
    SELECT DISTINCT practitioner_id
    FROM __CANONICAL_SCHEMA__.affiliations
    WHERE location_id IN (p_keep_location_id, p_delete_location_id)
    ON CONFLICT DO NOTHING;

    UPDATE __CANONICAL_SCHEMA__.locations keep_location
    SET
        org_id = COALESCE(keep_location.org_id, delete_location.org_id),
        name = COALESCE(NULLIF(keep_location.name, ''), delete_location.name),
        address = COALESCE(NULLIF(keep_location.address, ''), delete_location.address),
        locality = COALESCE(NULLIF(keep_location.locality, ''), delete_location.locality),
        region = COALESCE(NULLIF(keep_location.region, ''), delete_location.region),
        postal_code = COALESCE(NULLIF(keep_location.postal_code, ''), delete_location.postal_code),
        country_code = COALESCE(NULLIF(keep_location.country_code, ''), delete_location.country_code),
        country_name = COALESCE(NULLIF(keep_location.country_name, ''), delete_location.country_name),
        latitude = COALESCE(keep_location.latitude, delete_location.latitude),
        longitude = COALESCE(keep_location.longitude, delete_location.longitude),
        phone = COALESCE(NULLIF(keep_location.phone, ''), delete_location.phone),
        email = COALESCE(NULLIF(keep_location.email, ''), delete_location.email),
        website = COALESCE(NULLIF(keep_location.website, ''), delete_location.website),
        price_text = COALESCE(NULLIF(keep_location.price_text, ''), delete_location.price_text),
        rating = COALESCE(keep_location.rating, delete_location.rating),
        review_count = GREATEST(COALESCE(keep_location.review_count, 0), COALESCE(delete_location.review_count, 0)),
        verification_status = CASE
            WHEN keep_location.verification_status = 'unverified' THEN delete_location.verification_status
            ELSE keep_location.verification_status
        END
    FROM __CANONICAL_SCHEMA__.locations delete_location
    WHERE keep_location.id = p_keep_location_id
      AND delete_location.id = p_delete_location_id;

    DELETE FROM __CANONICAL_SCHEMA__.offerings loser
    USING __CANONICAL_SCHEMA__.offerings winner
    WHERE loser.location_id = p_delete_location_id
      AND winner.location_id = p_keep_location_id
      AND winner.source_id IS NOT DISTINCT FROM loser.source_id
      AND COALESCE(winner.raw_name, '') = COALESCE(loser.raw_name, '');

    UPDATE __CANONICAL_SCHEMA__.offerings
    SET location_id = p_keep_location_id
    WHERE location_id = p_delete_location_id;

    INSERT INTO __CANONICAL_SCHEMA__.entity_tags(entity_type, entity_id, tag_id)
    SELECT entity_type, p_keep_location_id, tag_id
    FROM __CANONICAL_SCHEMA__.entity_tags
    WHERE entity_type = 'location'
      AND entity_id = p_delete_location_id
    ON CONFLICT DO NOTHING;

    DELETE FROM __CANONICAL_SCHEMA__.entity_tags
    WHERE entity_type = 'location'
      AND entity_id = p_delete_location_id;

    DELETE FROM __CANONICAL_SCHEMA__.images loser
    USING __CANONICAL_SCHEMA__.images winner
    WHERE loser.entity_type = 'location'
      AND loser.entity_id = p_delete_location_id
      AND winner.entity_type = 'location'
      AND winner.entity_id = p_keep_location_id
      AND winner.blob_url = loser.blob_url;

    UPDATE __CANONICAL_SCHEMA__.images
    SET entity_id = p_keep_location_id
    WHERE entity_type = 'location'
      AND entity_id = p_delete_location_id;

    UPDATE __CANONICAL_SCHEMA__.source_records
    SET entity_id = p_keep_location_id
    WHERE entity_type = 'location'
      AND entity_id = p_delete_location_id;

    UPDATE __CANONICAL_SCHEMA__.reviews
    SET location_id = p_keep_location_id
    WHERE location_id = p_delete_location_id;

    DELETE FROM __CANONICAL_SCHEMA__.external_place_matches loser
    USING __CANONICAL_SCHEMA__.external_place_matches winner
    WHERE loser.location_id = p_delete_location_id
      AND winner.location_id = p_keep_location_id
      AND winner.provider = loser.provider;

    UPDATE __CANONICAL_SCHEMA__.external_place_matches
    SET location_id = p_keep_location_id
    WHERE location_id = p_delete_location_id;

    UPDATE __CANONICAL_SCHEMA__.external_reviews
    SET location_id = p_keep_location_id
    WHERE location_id = p_delete_location_id;

    DELETE FROM __CANONICAL_SCHEMA__.affiliations loser
    USING __CANONICAL_SCHEMA__.affiliations winner
    WHERE loser.location_id = p_delete_location_id
      AND winner.location_id = p_keep_location_id
      AND winner.practitioner_id = loser.practitioner_id
      AND winner.org_id IS NOT DISTINCT FROM loser.org_id;

    UPDATE __CANONICAL_SCHEMA__.affiliations
    SET location_id = p_keep_location_id
    WHERE location_id = p_delete_location_id;

    UPDATE __CANONICAL_SCHEMA__.clinic_claims
    SET location_id = p_keep_location_id
    WHERE location_id = p_delete_location_id;

    UPDATE __CANONICAL_SCHEMA__.listing_submissions
    SET target_entity_id = p_keep_location_id
    WHERE target_entity_type = 'location'
      AND target_entity_id = p_delete_location_id;

    DELETE FROM __CANONICAL_SCHEMA__.search_index
    WHERE entity_type = 'location'
      AND entity_id = p_delete_location_id;

    DELETE FROM __CANONICAL_SCHEMA__.locations
    WHERE id = p_delete_location_id;

    INSERT INTO __CANONICAL_SCHEMA__.entity_change_events(entity_type, entity_id, action, actor_type, actor_id, reason, metadata)
    VALUES (
        'location',
        p_keep_location_id,
        'merge_locations',
        'admin',
        p_actor_id,
        p_reason,
        jsonb_build_object('deleted_location_id', p_delete_location_id)
    );

    PERFORM __CANONICAL_SCHEMA__.refresh_search_index_for_location(p_keep_location_id);

    FOR affected_practitioner_id IN SELECT practitioner_id FROM fountain_affected_practitioners LOOP
        PERFORM __CANONICAL_SCHEMA__.refresh_search_index_for_practitioner(affected_practitioner_id);
    END LOOP;
END;
$$;

CREATE OR REPLACE FUNCTION __CANONICAL_SCHEMA__.replace_location_offerings(
    p_location_id INTEGER,
    p_offerings JSONB,
    p_actor_id UUID DEFAULT NULL
)
RETURNS INTEGER
LANGUAGE plpgsql
AS $$
DECLARE
    inserted_count INTEGER;
BEGIN
    IF jsonb_typeof(p_offerings) <> 'array' THEN
        RAISE EXCEPTION 'p_offerings must be a JSON array';
    END IF;

    IF NOT EXISTS (SELECT 1 FROM __CANONICAL_SCHEMA__.locations WHERE id = p_location_id) THEN
        RAISE EXCEPTION 'Location % does not exist', p_location_id;
    END IF;

    PERFORM __CANONICAL_SCHEMA__.set_mutation_actor(p_actor_id, 'admin');

    DELETE FROM __CANONICAL_SCHEMA__.offerings
    WHERE location_id = p_location_id;

    INSERT INTO __CANONICAL_SCHEMA__.offerings(
        location_id,
        treatment_id,
        raw_name,
        price_amount,
        price_currency,
        source_offer_url,
        source_id,
        data_origin,
        verification_status
    )
    SELECT
        p_location_id,
        treatment_id,
        raw_name,
        price_amount,
        price_currency,
        source_offer_url,
        source_id,
        'manual',
        'unverified'
    FROM jsonb_to_recordset(p_offerings) AS offering(
        treatment_id INTEGER,
        raw_name TEXT,
        price_amount DOUBLE PRECISION,
        price_currency TEXT,
        source_offer_url TEXT,
        source_id INTEGER
    )
    WHERE COALESCE(raw_name, '') <> '';

    GET DIAGNOSTICS inserted_count = ROW_COUNT;
    PERFORM __CANONICAL_SCHEMA__.refresh_search_index_for_location(p_location_id);
    RETURN inserted_count;
END;
$$;

