-- Marketplace database hardening.
--
-- Neon is now the production source of truth. This migration makes the
-- imported SQLite-shaped serving schema safe for incremental writes by adding
-- database-generated IDs, stable public IDs, lifecycle metadata, audit tables,
-- search refresh functions, and transaction-safe mutation helpers.

CREATE EXTENSION IF NOT EXISTS pgcrypto;

DO $$
BEGIN
    IF to_regclass('__CANONICAL_SCHEMA__.locations') IS NULL THEN
        RAISE EXCEPTION 'Missing %.locations. Run the Postgres bootstrap before applying serving-schema migrations.', '__CANONICAL_SCHEMA__';
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS __CANONICAL_SCHEMA__.accounts (
