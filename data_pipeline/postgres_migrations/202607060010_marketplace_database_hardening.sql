CREATE OR REPLACE FUNCTION __CANONICAL_SCHEMA__.refresh_offering_search_index_trigger()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP IN ('UPDATE', 'DELETE') THEN
        PERFORM __CANONICAL_SCHEMA__.refresh_search_index_for_location(OLD.location_id);
    END IF;

    IF TG_OP IN ('INSERT', 'UPDATE') AND (TG_OP <> 'UPDATE' OR NEW.location_id IS DISTINCT FROM OLD.location_id) THEN
        PERFORM __CANONICAL_SCHEMA__.refresh_search_index_for_location(NEW.location_id);
    END IF;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION __CANONICAL_SCHEMA__.refresh_affiliation_search_index_trigger()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP IN ('UPDATE', 'DELETE') THEN
        PERFORM __CANONICAL_SCHEMA__.refresh_search_index_for_practitioner(OLD.practitioner_id);
    END IF;

    IF TG_OP IN ('INSERT', 'UPDATE') AND (TG_OP <> 'UPDATE' OR NEW.practitioner_id IS DISTINCT FROM OLD.practitioner_id) THEN
        PERFORM __CANONICAL_SCHEMA__.refresh_search_index_for_practitioner(NEW.practitioner_id);
    END IF;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION __CANONICAL_SCHEMA__.refresh_entity_tag_search_index_trigger()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP IN ('UPDATE', 'DELETE') THEN
        IF OLD.entity_type = 'location' THEN
            PERFORM __CANONICAL_SCHEMA__.refresh_search_index_for_location(OLD.entity_id);
        ELSIF OLD.entity_type = 'practitioner' THEN
            PERFORM __CANONICAL_SCHEMA__.refresh_search_index_for_practitioner(OLD.entity_id);
        ELSIF OLD.entity_type = 'document' THEN
            PERFORM __CANONICAL_SCHEMA__.refresh_search_index_for_document(OLD.entity_id);
        END IF;
    END IF;

    IF TG_OP IN ('INSERT', 'UPDATE') THEN
        IF NEW.entity_type = 'location' THEN
            PERFORM __CANONICAL_SCHEMA__.refresh_search_index_for_location(NEW.entity_id);
        ELSIF NEW.entity_type = 'practitioner' THEN
            PERFORM __CANONICAL_SCHEMA__.refresh_search_index_for_practitioner(NEW.entity_id);
        ELSIF NEW.entity_type = 'document' THEN
            PERFORM __CANONICAL_SCHEMA__.refresh_search_index_for_document(NEW.entity_id);
        END IF;
    END IF;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;

