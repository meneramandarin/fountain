CREATE OR REPLACE FUNCTION __CANONICAL_SCHEMA__.refresh_search_index()
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
    entity RECORD;
BEGIN
    DELETE FROM __CANONICAL_SCHEMA__.search_index;

    FOR entity IN SELECT id FROM __CANONICAL_SCHEMA__.locations ORDER BY id LOOP
        PERFORM __CANONICAL_SCHEMA__.refresh_search_index_for_location(entity.id);
    END LOOP;

    FOR entity IN SELECT id FROM __CANONICAL_SCHEMA__.practitioners ORDER BY id LOOP
        PERFORM __CANONICAL_SCHEMA__.refresh_search_index_for_practitioner(entity.id);
    END LOOP;

    FOR entity IN SELECT id FROM __CANONICAL_SCHEMA__.documents ORDER BY id LOOP
        PERFORM __CANONICAL_SCHEMA__.refresh_search_index_for_document(entity.id);
    END LOOP;
END;
$$;

CREATE OR REPLACE FUNCTION __CANONICAL_SCHEMA__.refresh_location_search_index_trigger()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    affected_practitioner_id INTEGER;
BEGIN
    IF TG_OP = 'DELETE' THEN
        DELETE FROM __CANONICAL_SCHEMA__.search_index
        WHERE entity_type = 'location'
          AND entity_id = OLD.id;

        FOR affected_practitioner_id IN
            SELECT practitioner_id
            FROM __CANONICAL_SCHEMA__.affiliations
            WHERE location_id = OLD.id
        LOOP
            PERFORM __CANONICAL_SCHEMA__.refresh_search_index_for_practitioner(affected_practitioner_id);
        END LOOP;

        RETURN OLD;
    END IF;

    PERFORM __CANONICAL_SCHEMA__.refresh_search_index_for_location(NEW.id);

    FOR affected_practitioner_id IN
        SELECT practitioner_id
        FROM __CANONICAL_SCHEMA__.affiliations
        WHERE location_id = NEW.id
    LOOP
        PERFORM __CANONICAL_SCHEMA__.refresh_search_index_for_practitioner(affected_practitioner_id);
    END LOOP;

    RETURN NEW;
END;
$$;

