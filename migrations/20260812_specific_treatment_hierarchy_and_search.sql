    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'fountain'
      AND table_name = 'sources'
      AND column_name = 'offering_granularity'
  ) THEN
    RAISE EXCEPTION 'Retired source offering granularity column still exists';
  END IF;

  IF EXISTS (
    WITH RECURSIVE ancestry AS (
      SELECT id AS origin_id, parent_treatment_id, ARRAY[id] AS visited
      FROM fountain.treatments
      UNION ALL
      SELECT ancestry.origin_id, parent.parent_treatment_id, ancestry.visited || parent.id
      FROM ancestry
      JOIN fountain.treatments parent ON parent.id = ancestry.parent_treatment_id
      WHERE NOT parent.id = ANY(ancestry.visited)
    )
    SELECT 1 FROM ancestry WHERE parent_treatment_id = ANY(visited)
  ) THEN
    RAISE EXCEPTION 'Treatment hierarchy contains a cycle';
  END IF;
END;
$$;

