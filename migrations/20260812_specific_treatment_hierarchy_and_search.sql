CREATE OR REPLACE FUNCTION fountain.treatment_descendants(p_treatment_id integer)
RETURNS TABLE(id integer)
LANGUAGE sql
STABLE
PARALLEL SAFE
AS $$
  WITH RECURSIVE treatment_tree(id, visited) AS (
    SELECT treatment.id, ARRAY[treatment.id]
    FROM fountain.treatments treatment
    WHERE treatment.id = p_treatment_id
    UNION ALL
    SELECT child.id, treatment_tree.visited || child.id
    FROM fountain.treatments child
    JOIN treatment_tree ON child.parent_treatment_id = treatment_tree.id
    WHERE NOT child.id = ANY(treatment_tree.visited)
  )
  SELECT treatment_tree.id FROM treatment_tree
$$;

