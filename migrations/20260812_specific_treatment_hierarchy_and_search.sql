CREATE TEMP TABLE offering_specific_assignments ON COMMIT DROP AS
WITH maximum_priority AS (
  SELECT offering_id, max(priority) AS priority
  FROM offering_specific_candidates
  GROUP BY offering_id
), eligible AS (
  SELECT candidate.offering_id,
         min(candidate.previous_treatment_id) AS previous_treatment_id,
         min(candidate.target_treatment_id) AS target_treatment_id
  FROM offering_specific_candidates candidate
  JOIN maximum_priority maximum
    ON maximum.offering_id = candidate.offering_id
   AND maximum.priority = candidate.priority
